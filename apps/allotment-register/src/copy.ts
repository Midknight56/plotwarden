const text = (value: unknown): string | undefined => (value === undefined || value === null || value === "" ? undefined : String(value));

/** Words for an error from an allotment command. A code it does not own goes to the shared words. */
export function allotError(t: T, error: DomainError): string {
  const d = error.detail;
  switch (error.code) {
    case "plot_not_free":
    case "tenancy_overlap": {
      const sourceRef = text(d?.["sourceRef"]);
      const start = text(d?.["start"]);
      const base = error.code === "plot_not_free" ? "err_plot_not_free" : "err_tenancy_overlap";
      return sourceRef === undefined || start === undefined ? t(base) : t(`${base}_ref`, { sourceRef, start });
    }
    case "invalid_input": {
      const first = error.fields?.[0];
      if (first === undefined) break;
      if (first.field.startsWith("skipReason:")) return t("err_skip_reason_required");
      const field = t(`field_${first.field}`);
      if (first.code === "required") return first.field === "choice" ? t("chooseChoice") : t("enterField", { field });
      if (first.code === "invalid_date") return t("invalidDate");
      if (first.code === "bad_amount") return t("enterAmount");
      return t("checkFieldShort", { field, reason: t(`reason_${first.code}`) });
    }
    default: {
      const key = CODE_WORDS[error.code];
      if (key !== undefined) return t(key);
    }
  }
  return errorMessage(t, error);
}
