/** What a payment says: the amount and what is still due, or "Paid in full." for the last one. */
export function paymentMessage(t: T, amount: number, balance: number, currency: string): string {
  if (balance === 0) return t("paidInFull");
  return t("paymentRecorded", { amount: formatMoney(amount, currency as Currency), balance: formatMoney(balance, currency as Currency) });
}

