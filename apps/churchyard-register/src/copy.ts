/** Words for an error from a church command. A code it does not own goes to the shared words. */
export function churchError(t: T, error: DomainError): string {
  const sourceRef = error.detail?.["sourceRef"];
  const ref = sourceRef === undefined ? undefined : String(sourceRef);
  switch (error.code) {
    case "space_reserved":
      return ref === undefined ? t("spaceReservedNoRef") : t("spaceReservedRef", { sourceRef: ref });
    case "claim_overlap":
      return ref === undefined ? t("heldNoRef") : t("heldRef", { sourceRef: ref });
    case "invalid_input": {
      const first = error.fields?.[0];
      if (first === undefined) break;
      const field = t(FIELD_WORDS[first.field] ?? first.field);
      if (first.code === "required") return t("enterField", { field });
      if (first.code === "name_and_unknown") return t("nameAndUnknown");
      if (first.code === "invalid_date") return t("invalidDate");
      if (first.code === "no_year") return t("noYear");
      return t("checkFieldShort", { field, reason: t(`reason_${first.code}`) });
    }
    default: {
      const key = CODE_WORDS[error.code];
      if (key !== undefined) return t(key);
    }
  }
  return errorMessage(t, error);
}
