// T35 (spec 06, task 6.4): the copy catalog. Every catalog value is plain words with no dash between them,
// no value names a provider or a tool, every control in the UI source has an accessible name from the
// catalog, every state has its sentence, and every file of artwork is in the ledger. Requirements Z9, R23.1.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { ALLOT_COPY } from "../../apps/allotment-register/src/copy";
import { CHURCH_COPY } from "../../apps/churchyard-register/src/copy";
import { MARKET_COPY } from "../../examples/market/src/copy";
import { COPY, ERROR_ACTIONS, errorText } from "../../template/src/ui/copy";

const ROOT = join(__dirname, "..", "..");
const catalogs: [string, Readonly<Record<string, string>>][] = [
  ["shared", COPY],
  ["churchyard", CHURCH_COPY],
  ["allotment", ALLOT_COPY],
  ["market", MARKET_COPY],
];

describe("the merged catalogs", () => {
  it("hold a good number of words, each one a non empty text", () => {
    for (const [name, catalog] of catalogs) {
      const entries = Object.entries(catalog);
      expect(entries.length, name).toBeGreaterThan(20);
      for (const [key, value] of entries) {
        expect(typeof value, `${name}.${key}`).toBe("string");
        expect(value.trim(), `${name}.${key}`).not.toBe("");
      }
    }
  });

  it("hold no dash between words: no en dash, no em dash, no spaced hyphen, no double hyphen", () => {
    const bad: string[] = [];
    for (const [name, catalog] of catalogs) {
      for (const [key, value] of Object.entries(catalog)) {
        if (/[\u2012\u2013\u2014\u2015\u2212]/.test(value) || /\s-+\s/.test(value) || /\w--\w/.test(value) || /\s-\w/.test(value.replace(/^-/, ""))) bad.push(`${name}.${key}: ${value}`);
      }
    }
    expect(bad).toEqual([]);
  });

  it("hold the middle dot only as the separator of a summary", () => {
    for (const [name, catalog] of catalogs) {
      for (const [key, value] of Object.entries(catalog)) {
        if (!value.includes("\u00b7")) continue;
        // Every middle dot sits between two spaces, as in "Y07 · Yew Walk · Taken".
        expect(/[^ ]\u00b7|\u00b7[^ ]/.test(value), `${name}.${key}: ${value}`).toBe(false);
      }
    }
  });

  it("name no provider, no tool that built the app and no assistant", () => {
    const WORDS = /\b(powered by|built with|made with|generated by|created by ai|assistant|chatbot|language model|artificial intelligence|machine learning|kiro)\b|\bAI\b/i;
    const bad: string[] = [];
    for (const [name, catalog] of catalogs) for (const [key, value] of Object.entries(catalog)) if (WORDS.test(value)) bad.push(`${name}.${key}: ${value}`);
    expect(bad).toEqual([]);
  });

  it("keep the two apps from taking each other's words: no church word in the garden and no garden word in the church", () => {
    // "Reserve for next applicant" and "Waiting list" are words the plan gives the churchyard, so they are not listed.
    const churchOnly = /\b(burial|burials|grave|reservation holder|family map|inscription)\b/i;
    const gardenOnly = /\b(tenancy|tenancies|season fee|season fees|rent)\b/i;
    for (const [key, value] of Object.entries(ALLOT_COPY)) expect(churchOnly.test(value), `allotment.${key}: ${value}`).toBe(false);
    for (const [key, value] of Object.entries(CHURCH_COPY)) expect(gardenOnly.test(value), `churchyard.${key}: ${value}`).toBe(false);
  });
});

