// ---- Accessible names in the UI source -------------------------------------------------------------------

function sourceFiles(): { rel: string; text: string }[] {
  const out: { rel: string; text: string }[] = [];
  const add = (dir: string) => {
    if (!existsSync(join(ROOT, dir))) return;
    for (const name of readdirSync(join(ROOT, dir))) if (name.endsWith(".tsx")) out.push({ rel: `${dir}/${name}`, text: readFileSync(join(ROOT, dir, name), "utf8") });
  };
  add("template/src/ui");
  add("apps/churchyard-register/src");
  add("apps/allotment-register/src");
  add("examples/market/src");
  return out;
}

interface Tag {
  name: string;
  head: string;
  /** What follows the opening tag up to its closing tag. Empty for a self closing tag. */
  body: string;
  line: number;
}

/** Read each opening tag of the given names, with braces and quotes honoured. */
function tagsOf(text: string, names: readonly string[]): Tag[] {
  const found: Tag[] = [];
  const pattern = new RegExp(`<(${names.join("|")})(?=[\\s/>])`, "g");
  for (const match of text.matchAll(pattern)) {
    let i = (match.index ?? 0) + match[0].length;
    let depth = 0;
    let quote = "";
    for (; i < text.length; i++) {
      const c = text[i] as string;
      if (quote !== "") {
        if (c === quote) quote = "";
        continue;
      }
      if (c === '"' || c === "'") {
        quote = c;
      } else if (c === "{") depth += 1;
      else if (c === "}") depth -= 1;
      else if (c === ">" && depth === 0 && text[i - 1] !== "=") break;
    }
    const head = text.slice(match.index ?? 0, i + 1);
    const selfClosing = head.endsWith("/>");
    let body = "";
    if (!selfClosing) {
      const close = text.indexOf(`</${match[1] as string}>`, i);
      body = close === -1 ? "" : text.slice(i + 1, close);
    }
    found.push({ name: match[1] as string, head, body, line: text.slice(0, match.index ?? 0).split("\n").length });
  }
  return found;
}

const hasProp = (head: string, prop: string): boolean => new RegExp(`\\s${prop}(=|\\s|/|>)`).test(head);
const hasContent = (body: string): boolean => body.replace(/<svg[\s\S]*?(<\/svg>|\/>)/g, "").trim() !== "";

describe("every control in the UI source has an accessible name", () => {
  const files = sourceFiles();

  it("finds the UI source to scan", () => {
    expect(files.length).toBeGreaterThanOrEqual(30);
  });

  it("gives each native button and link text or an aria label", () => {
    const bad: string[] = [];
    for (const { rel, text } of files) for (const tag of tagsOf(text, ["button", "a"])) if (!hasProp(tag.head, "aria-label") && !hasProp(tag.head, "aria-labelledby") && !hasContent(tag.body)) bad.push(`${rel}:${tag.line} <${tag.name}>`);
    expect(bad).toEqual([]);
  });

  it("gives each Button and ButtonLink children or an aria label", () => {
    const bad: string[] = [];
    for (const { rel, text } of files) {
      for (const tag of tagsOf(text, ["Button", "ButtonLink"])) {
        if (/\.\.\.rest|\.\.\.props/.test(tag.head)) continue;
        if (!hasProp(tag.head, "aria-label") && !hasContent(tag.body) && !/\bchildren=/.test(tag.head)) bad.push(`${rel}:${tag.line} <${tag.name}>`);
      }
    }
    expect(bad).toEqual([]);
  });

  it("gives each field component a label and each radio group a legend", () => {
    const bad: string[] = [];
    for (const { rel, text } of files) {
      for (const tag of tagsOf(text, ["TextField", "TextArea", "SelectField", "CheckField"])) if (!hasProp(tag.head, "label")) bad.push(`${rel}:${tag.line} <${tag.name}>`);
      for (const tag of tagsOf(text, ["RadioGroup"])) if (!hasProp(tag.head, "legend")) bad.push(`${rel}:${tag.line} <RadioGroup>`);
    }
    expect(bad).toEqual([]);
  });

  it("gives each raw input, select and textarea a label around it, a label for it, or an aria label", () => {
    const bad: string[] = [];
    for (const { rel, text } of files) {
      for (const tag of tagsOf(text, ["input", "select", "textarea"])) {
        if (/type="hidden"/.test(tag.head)) continue;
        const index = text.split("\n").slice(0, tag.line).join("\n").length;
        const before = text.slice(Math.max(0, index - 500), index);
        const insideLabel = before.lastIndexOf("<label") > before.lastIndexOf("</label>");
        if (!insideLabel && !hasProp(tag.head, "aria-label") && !hasProp(tag.head, "aria-labelledby") && !hasProp(tag.head, "id")) bad.push(`${rel}:${tag.line} <${tag.name}>`);
      }
    }
    expect(bad).toEqual([]);
  });

  it("gives each dialog a name, each image an alt, and each drawing a label or a hidden mark", () => {
    const bad: string[] = [];
    for (const { rel, text } of files) {
      for (const tag of tagsOf(text, ["dialog"])) if (!hasProp(tag.head, "aria-label") && !hasProp(tag.head, "aria-labelledby")) bad.push(`${rel}:${tag.line} <dialog>`);
      for (const tag of tagsOf(text, ["img"])) if (!hasProp(tag.head, "alt")) bad.push(`${rel}:${tag.line} <img>`);
      for (const tag of tagsOf(text, ["svg"])) {
        const named = hasProp(tag.head, "aria-label") || hasProp(tag.head, "aria-labelledby") || /<title[\s>]/.test(tag.body);
        const hidden = /aria-hidden/.test(tag.head);
        if (!named && !hidden) bad.push(`${rel}:${tag.line} <svg>`);
      }
    }
    expect(bad).toEqual([]);
  });

  it("takes every aria label, title and alt from an expression, never a literal", () => {
    const bad: string[] = [];
    for (const { rel, text } of files) {
      text.split("\n").forEach((line, i) => {
        for (const m of line.matchAll(/\b(aria-label|aria-description|title|alt|placeholder)="([^"]*[A-Za-z][^"]*)"/g)) bad.push(`${rel}:${i + 1} ${m[1] as string}="${m[2] as string}"`);
      });
    }
    expect(bad).toEqual([]);
  });
});

// ---- Artwork ledger -------------------------------------------------------------------------------------

describe("the artwork ledger", () => {
  const ledger = readFileSync(join(ROOT, "assets", "origins.md"), "utf8");
  const files = readdirSync(join(ROOT, "assets")).filter((f) => f !== "origins.md");

  it("lists every file of artwork by name", () => {
    expect(files.length).toBeGreaterThanOrEqual(4);
    expect(files.filter((f) => !ledger.includes(`\`${f}\``))).toEqual([]);
  });

  it("says where each file is used and that no real grave, person or place is shown", () => {
    expect(ledger).toMatch(/no real grave/i);
    expect(ledger).toMatch(/no real (site plan|person)/i);
    expect(ledger).toMatch(/invented places/i);
    for (const f of files) {
      const row = ledger.split("\n").find((line) => line.startsWith("|") && line.includes(`\`${f}\``)) ?? "";
      expect(row.split("|").map((c) => c.trim()).filter(Boolean).length, f).toBeGreaterThanOrEqual(3);
    }
  });

  it("holds no text, script, link or font in any drawing", () => {
    for (const f of files.filter((n) => n.endsWith(".svg"))) {
      const svg = readFileSync(join(ROOT, "assets", f), "utf8");
      expect(/<script|<text|<foreignObject|xlink:href|href="http|font-family|@import|url\(http/i.test(svg), f).toBe(false);
    }
  });
});
