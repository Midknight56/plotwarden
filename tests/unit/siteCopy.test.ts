// The hub and the two visitor pages (spec 06, task 6.17, requirement Z10 and Z9 for the site).
// What the pages say, what they link to, and that they are built from the one catalog in `site/src/copy.ts`.
// The pages run in the browser specs. Here they are drawn to static markup and read.
import { readFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import { Home, hubRouteOf, hubTitleOf } from "../../site/src/Home";
import { VisitorLanding, visitorRouteOf, visitorTitleOf } from "../../site/src/VisitorLanding";
import { SITE_COPY } from "../../site/src/copy";
import { PRACTICE_MAPS } from "../../site/src/practiceMaps";
import { buildPracticeMaps } from "../../tools/site/practiceMaps";
import { buildVisitorFiles } from "../../tools/site/visitorFiles";

const read = (rel: string): string => readFileSync(new URL(`../../${rel}`, import.meta.url), "utf8");

/** The text of a page as a person reads it: no tags, one space between words. */
const textOf = (html: string): string => html.replace(/<[^>]*>/g, " ").replace(/&amp;/g, "&").replace(/&#x27;/g, "'").replace(/\s+/g, " ").trim();

const hub = (hash = ""): string => renderToStaticMarkup(createElement(Home, { route: hubRouteOf(hash) }));
const visitor = (kind: "family" | "seeker", hash = ""): string => {
  const file = kind === "family" ? "family-map-2026-04-20.html" : "availability-map-2026-04-20.html";
  return renderToStaticMarkup(createElement(VisitorLanding, { kind, file, route: visitorRouteOf(hash) }));
};

const links = (html: string): { text: string; href: string; download: boolean }[] =>
  [...html.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/g)].map((m) => ({
    text: textOf(m[2] as string),
    href: /href="([^"]*)"/.exec(m[1] as string)?.[1] ?? "",
    download: /\bdownload\b/.test(m[1] as string),
  }));

describe("site catalog", () => {
  const entries = Object.entries(SITE_COPY);

  it("has a word for every key and no empty one", () => {
    expect(entries.length).toBeGreaterThan(30);
    for (const [key, value] of entries) expect(value.trim(), key).not.toBe("");
  });

  it("holds no dash between words: no en dash, no em dash, no spaced hyphen, no double hyphen", () => {
    for (const [key, value] of entries) {
      expect(value, key).not.toMatch(/[\u2012-\u2015\u2212]/);
      expect(value, key).not.toMatch(/\s-{1,2}\s/);
      expect(value, key).not.toMatch(/--/);
    }
  });

  it("names no tool, no assistant and no maker, and does not say powered by or built with", () => {
    for (const [key, value] of entries) {
      expect(value, key).not.toMatch(/powered by|built with|made with|generated by|assistant|chatbot|artificial intelligence|\bAI\b|\bKiro\b/i);
    }
  });

  it("says the one line of the product exactly", () => {
    expect(SITE_COPY.tagline).toBe("Plotwarden keeps plot registers on the keeper's own device.");
  });

  it("says the update notice exactly", () => {
    expect(SITE_COPY.updateReady).toBe("A new version is ready. Save your work before reopening.");
  });

  it("is the same wording as the static 404 page and the static pages' titles and no script note", () => {
    const notFound = read("site/public/404.html");
    expect(notFound).toContain(`<title>${SITE_COPY.notFoundTitle} · ${SITE_COPY.siteName}</title>`);
    expect(notFound).toContain(`<h1>${SITE_COPY.notFoundTitle}</h1>`);
    expect(notFound).toContain(`<p>${SITE_COPY.notFoundLine}</p>`);
    expect(notFound).toContain(`<a href="/">${SITE_COPY.notFoundOpen}</a>`);
    expect(read("site/index.html")).toContain(`<title>${SITE_COPY.siteName}</title>`);
    expect(read("site/visitor/family/index.html")).toContain(`<title>${visitorTitleOf("family", "home")}</title>`);
    expect(read("site/visitor/seeker/index.html")).toContain(`<title>${visitorTitleOf("seeker", "home")}</title>`);
    for (const page of ["site/index.html", "site/visitor/family/index.html", "site/visitor/seeker/index.html"]) {
      expect(read(page)).toContain(`<noscript>${SITE_COPY.noScript}</noscript>`);
    }
  });
});

describe("the static pages", () => {
  it.each([
    ["site/index.html", "home", undefined],
    ["site/visitor/family/index.html", "family", "family-map-2026-04-20.html"],
    ["site/visitor/seeker/index.html", "seeker", "availability-map-2026-04-20.html"],
  ])("%s is a page with a language, a viewport, one root and one module script, and no inline script or style", (path, page, file) => {
    const html = read(path);
    expect(html).toMatch(/<html lang="en-GB">/);
    expect(html).toMatch(/<meta name="viewport" content="width=device-width, initial-scale=1"/);
    expect(html).toContain(`<body data-page="${page}"${file === undefined ? "" : ` data-file="${file}"`}>`);
    expect((html.match(/<div id="root"><\/div>/g) ?? []).length).toBe(1);
    expect((html.match(/<script\b/g) ?? []).length).toBe(1);
    expect(html).toMatch(/<script type="module" src="[^"]+src\/main\.tsx"><\/script>/);
    expect(html).not.toMatch(/<style\b|\sstyle=|\sonclick=|<script>[^<]/);
    expect(html).not.toMatch(/https?:\/\//);
  });

  it("name the files that the build writes", () => {
    const files = buildVisitorFiles();
    expect(read("site/visitor/family/index.html")).toContain(`data-file="${files.family.fileName}"`);
    expect(read("site/visitor/seeker/index.html")).toContain(`data-file="${files.seeker.fileName}"`);
  });
});

describe("the hub", () => {
  it("reads a hash as a route, and any other hash as not found", () => {
    expect(hubRouteOf("")).toBe("home");
    expect(hubRouteOf("#")).toBe("home");
    expect(hubRouteOf("#/")).toBe("home");
    expect(hubRouteOf("#/about")).toBe("about");
    expect(hubRouteOf("#/about/")).toBe("about");
    expect(hubRouteOf("#/nope")).toBe("not-found");
    expect(hubRouteOf("#/about/more")).toBe("not-found");
    expect(hubRouteOf("#/r/abc/map")).toBe("not-found");
  });

  it("gives each route its own title", () => {
    expect(hubTitleOf("home")).toBe("Plotwarden");
    expect(hubTitleOf("about")).toBe("About Plotwarden · Plotwarden");
    expect(hubTitleOf("not-found")).toBe("Page not found · Plotwarden");
  });

  it("says in one line what Plotwarden is, under one heading", () => {
    const html = hub();
    expect((html.match(/<h1\b/g) ?? []).length).toBe(1);
    expect(html).toMatch(/<h1[^>]*>Plotwarden<\/h1>/);
    expect(textOf(html)).toContain("Plotwarden keeps plot registers on the keeper's own device.");
    expect((textOf(html).match(/keeps plot registers/g) ?? []).length).toBe(1);
  });

  it("offers the two registers and the Desk preview as clear choices, each with its own name", () => {
    const html = hub();
    const list = links(html);
    expect(list.find((l) => l.text === "Open Review Desk preview")?.href).toBe("review/");
    expect(html).toContain(">Churchyard Register<");
    expect(html).toContain(">Allotment Register<");
    expect(html).toContain(">Plotwarden Review Desk<");
    // The two registers are no longer one link each. Each has a practice button and a start button.
    expect(list.find((l) => l.text === "Open Churchyard Register")).toBeUndefined();
    expect(list.find((l) => l.text === "Open Allotment Register")).toBeUndefined();
  });

  it("says the job in the first line under the heading, and keeps the line about the device under it", () => {
    const html = hub();
    expect(SITE_COPY.jobLine).toBe("Find a burial. Offer a garden plot. Keep the history of both.");
    expect(html).toMatch(/<\/h1><p[^>]*>Find a burial\. Offer a garden plot\. Keep the history of both\.<\/p>/);
    const text = textOf(html);
    expect(text.indexOf(SITE_COPY.jobLine)).toBeGreaterThan(-1);
    expect(text.indexOf(SITE_COPY.jobLine)).toBeLessThan(text.indexOf(SITE_COPY.tagline));
    expect(text.indexOf(SITE_COPY.tagline)).toBeLessThan(text.indexOf("Churchyard Register Find a burial, give"));
  });

  /** The two register cards, each as the markup between its `<article` and `</article>`. */
  const cards = (): { name: string; html: string }[] =>
    [...hub().matchAll(/<article\b[^>]*>([\s\S]*?)<\/article>/g)].map((m) => ({ name: textOf(/<h3[^>]*>([\s\S]*?)<\/h3>/.exec(m[1] as string)?.[1] ?? ""), html: m[1] as string }));

  it("gives each register a card with its name, one line, a drawing, and two buttons: one to try and one to start", () => {
    const found = cards();
    expect(found.map((c) => c.name)).toEqual(["Churchyard Register", "Allotment Register"]);
    for (const [card, folder, line] of [
      [found[0], "churchyard/", SITE_COPY.churchyardLine],
      [found[1], "allotments/", SITE_COPY.allotmentLine],
    ] as const) {
      const here = links(card?.html ?? "");
      expect(here.map((l) => l.text), card?.name).toEqual(["Try the practice register", "Start your own"]);
      expect(here[0]?.href).toBe(`${folder}#/practice`);
      expect(here[1]?.href).toBe(`${folder}#/new`);
      expect(textOf(card?.html ?? "")).toContain(line);
      // The button's own name says which register, and keeps the words that show on it.
      for (const m of (card?.html ?? "").matchAll(/<a\b[^>]*aria-label="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g)) {
        expect(m[1], card?.name).toContain(textOf(m[2] as string));
        expect(m[1], card?.name).toContain(card?.name);
      }
    }
  });

  it("draws each practice map with the shared sheet: inline svg, no image file, no address, a name, and the plots of the hand totals", () => {
    const [church, garden] = cards();
    for (const card of [church, garden]) {
      const html = card?.html ?? "";
      expect((html.match(/<svg\b[^>]*class="sheet"/g) ?? []).length, card?.name).toBe(1);
      expect(html).not.toMatch(/<img\b|<image\b|url\(|https?:|\.svg|\.png|\.jpg|\.webp|<script/);
      expect(html).toMatch(/<svg\b[^>]*role="img"[^>]*aria-label="[^"]+"/);
      expect(html).toMatch(/viewBox="0 0 [\d.]+ [\d.]+"/);
    }
    expect(church?.html).toContain(`aria-label="${SITE_COPY.churchyardMapLabel}"`);
    expect(garden?.html).toContain(`aria-label="${SITE_COPY.allotmentMapLabel}"`);
    const count = (html: string, pattern: RegExp): number => (html.match(pattern) ?? []).length;
    // Lantern Fold, hand totals 1: 12 plots. 6 taken, 2 reserved, 1 unusable, 3 free.
    expect(count(church?.html ?? "", /<path class="plot[ "]/g)).toBe(12);
    // Each plot carries its state as a class (spec 07, L6.2), and the counts are the hand totals.
    for (const [state, n] of [["taken", 6], ["reserved", 2], ["unusable", 1], ["free", 3]] as const) {
      expect(count(church?.html ?? "", new RegExp(`<path class="plot ${state}"`, "g")), `Lantern Fold, ${state}`).toBe(n);
    }
    expect(count(church?.html ?? "", /<circle class="mark solid"/g)).toBe(6);
    expect(count(church?.html ?? "", /<line class="mark"/g)).toBe(2);
    expect(count(church?.html ?? "", /<g class="mark">/g)).toBe(1);
    expect(church?.html).toContain("Main gate");
    // Thimble Beds, hand totals 2.1: 6 beds. 3 taken, 1 unusable, 2 free, none reserved.
    expect(count(garden?.html ?? "", /<polygon class="plot bed[ "]/g)).toBe(6);
    for (const [state, n] of [["taken", 3], ["reserved", 0], ["unusable", 1], ["free", 2]] as const) {
      expect(count(garden?.html ?? "", new RegExp(`<polygon class="plot bed ${state}"`, "g")), `Thimble Beds, ${state}`).toBe(n);
    }
    expect(count(garden?.html ?? "", /<circle class="mark solid"/g)).toBe(3);
    expect(count(garden?.html ?? "", /<line class="mark"/g)).toBe(0);
    expect(count(garden?.html ?? "", /<g class="mark">/g)).toBe(1);
    expect(garden?.html).toContain("Main gate");
  });

  it("holds no person name in either drawing", () => {
    for (const map of [PRACTICE_MAPS.church, PRACTICE_MAPS.garden]) {
      for (const name of ["Mirel Quillmoss", "Torin Pellwick", "Tavi Bramblequill", "Olin Reedwhorl", "Ada Stonecrop"]) expect(map).not.toContain(name);
    }
  });

  it("keeps the committed drawings equal to a fresh build from the practice data (npm run build:maps)", () => {
    expect(PRACTICE_MAPS).toEqual(buildPracticeMaps());
  });

  it("says the new words exactly, and no dash", () => {
    expect(SITE_COPY.tryPractice).toBe("Try the practice register");
    expect(SITE_COPY.startOwn).toBe("Start your own");
    expect(SITE_COPY.churchyardMapLabel).toBe("Practice map of Lantern Fold");
    expect(SITE_COPY.allotmentMapLabel).toBe("Practice map of Thimble Beds");
    expect(SITE_COPY).not.toHaveProperty("churchyardOpen");
    expect(SITE_COPY).not.toHaveProperty("allotmentOpen");
    for (const key of ["jobLine", "tryPractice", "startOwn", "churchyardMapLabel", "allotmentMapLabel"] as const) {
      expect(SITE_COPY[key], key).not.toMatch(/[\u2012-\u2015\u2212]|\s-{1,2}\s|--/);
    }
  });

  it("links the two sample sheets for visitors, and About", () => {
    const list = links(hub());
    expect(list.find((l) => l.text === "See the family map")?.href).toBe("visitor/family/");
    expect(list.find((l) => l.text === "See the plot seeker map")?.href).toBe("visitor/seeker/");
    expect(list.find((l) => l.text === "About")?.href).toBe("#/about");
  });

  it("has one main landmark, one named navigation, and no image without a name", () => {
    const html = hub();
    expect((html.match(/<main\b/g) ?? []).length).toBe(1);
    expect(html).toMatch(/<nav aria-label="Site"/);
    for (const img of html.matchAll(/<img\b[^>]*>/g)) expect(img[0]).toMatch(/\balt=/);
    expect(html).not.toMatch(/\sstyle=/);
    expect(html).not.toMatch(/https?:\/\//);
  });

  it("starts with the stripe in the three app colours and the bar with the brand and About, neither with a word on a picture", () => {
    const html = hub();
    expect(html).toMatch(/^<div class="stripe" aria-hidden="true"><\/div><header class="bar">/);
    const bar = /<header class="bar">([\s\S]*?)<\/header>/.exec(html)?.[1] ?? "";
    expect(textOf(bar)).toBe("Plotwarden About");
    expect(bar).toMatch(/<span class="brand">Plotwarden<\/span>/);
    expect(bar).not.toMatch(/<img\b|<svg\b|\.svg/);
    expect(html).not.toMatch(/class="sky/);
  });

  it("lays the two registers as doors, each with an art band that has no words and no control in it", () => {
    const html = hub();
    expect(html).toMatch(/<ul class="doors plain">/);
    const doors = [...html.matchAll(/<li class="door (church|garden)">([\s\S]*?)<\/li>/g)];
    expect(doors.map((d) => d[1])).toEqual(["church", "garden"]);
    for (const door of doors) {
      const art = /<div class="door-art" aria-hidden="true">([\s\S]*?)<\/div>/.exec(door[2] as string);
      expect(art, door[1]).not.toBeNull();
      expect(art?.[1], `${door[1]}: nothing in the band`).toBe("");
      expect(door[2], door[1]).toMatch(/<article\b[^>]*aria-labelledby="choice-(church|garden)"/);
      expect(door[2], door[1]).not.toMatch(/<img\b|\sstyle=/);
    }
  });

  it("puts the Review Desk in a card of its own, not an article, and the sheets for visitors after it, each with a picture drawn in code", () => {
    const html = hub();
    expect((html.match(/<article\b/g) ?? []).length, "only the two doors are articles").toBe(2);
    const desk = /<section class="review-card"[^>]*>([\s\S]*?)<\/section>/.exec(html);
    expect(desk, "the Review Desk card").not.toBeNull();
    expect(desk?.[1]).toMatch(/<h3[^>]*>Plotwarden Review Desk<\/h3>/);
    expect(links(desk?.[1] ?? "").map((l) => l.text)).toEqual(["Open Review Desk preview"]);
    const rows = [...html.matchAll(/<div class="sheet-row">([\s\S]*?)<\/div>/g)].map((m) => m[1] as string);
    expect(rows.length).toBe(2);
    rows.forEach((row, i) => {
      expect(row, `row ${i}`).toMatch(/^<span class="sheet-pic (church|garden)" aria-hidden="true"><\/span><a\b/);
      expect(textOf(row.replace(/<span class="sheet-pic[^>]*><\/span>/, "")), `row ${i}`).toBe(i === 0 ? "See the family map" : "See the plot seeker map");
    });
    expect(html.indexOf('class="review-card"')).toBeGreaterThan(html.indexOf('class="doors plain"'));
    expect(html.indexOf('class="sheet-row"')).toBeGreaterThan(html.indexOf('class="review-card"'));
  });

  it("keeps the links in the order of the page: About, each door twice, the Desk, then the two sheets", () => {
    expect(links(hub()).map((l) => l.text)).toEqual(["About", "Try the practice register", "Start your own", "Try the practice register", "Start your own", "Open Review Desk preview", "See the family map", "See the plot seeker map"]);
  });

  it("gives the page one stripe and the same bar to About and Page not found", () => {
    for (const hash of ["#/about", "#/nope"]) expect(hub(hash)).toMatch(/^<div class="stripe" aria-hidden="true"><\/div><header class="bar">/);
  });

  it("makes no claim on the home page that the places are invented, which About says", () => {
    expect(textOf(hub())).not.toMatch(/invented/i);
    expect(textOf(hub("#/about"))).toContain(SITE_COPY.aboutInvented);
  });

  it("About says it runs in the browser, names the invented places, and goes back to the start", () => {
    const html = hub("#/about");
    expect(html).toMatch(/<h1[^>]*>About Plotwarden<\/h1>/);
    const text = textOf(html);
    expect(text).toContain(SITE_COPY.aboutOffline);
    expect(text).toContain("Lantern Fold and Thimble Beds are invented places.");
    expect(links(html).find((l) => l.text === "Back to start")?.href).toBe("#/");
  });

  it("says Page not found for an unknown route, and goes back to the start", () => {
    const html = hub("#/nope");
    expect(html).toMatch(/<h1[^>]*>Page not found<\/h1>/);
    expect(textOf(html)).toContain("This address has no page on this site.");
    expect(links(html).find((l) => l.text === "Back to start")?.href).toBe("#/");
  });

  it("gives each heading a tab stop of its own so a route change can move focus to it", () => {
    for (const hash of ["", "#/about", "#/nope"]) expect(hub(hash)).toMatch(/<h1 tabindex="-1"/);
  });
});

describe("the visitor pages", () => {
  const cases = [
    { kind: "family", title: "Family map", open: "Open the family map", download: "Download the family map", file: "family-map-2026-04-20.html", place: "Lantern Fold" },
    { kind: "seeker", title: "Plot seeker map", open: "Open the plot seeker map", download: "Download the plot seeker map", file: "availability-map-2026-04-20.html", place: "Thimble Beds" },
  ] as const;

  it("reads a hash as a route", () => {
    expect(visitorRouteOf("")).toBe("home");
    expect(visitorRouteOf("#/")).toBe("home");
    expect(visitorRouteOf("#/about")).toBe("about");
    expect(visitorRouteOf("#/anything")).toBe("not-found");
  });

  it.each(cases)("$kind: one heading, what the sheet is, and where it came from", ({ kind, title, place }) => {
    const html = visitor(kind);
    expect((html.match(/<h1\b/g) ?? []).length).toBe(1);
    expect(html).toMatch(new RegExp(`<h1[^>]*>${title}</h1>`));
    expect(textOf(html)).toContain(`This copy was made from ${place}, an invented place.`);
  });

  it.each(cases)("$kind: opens and downloads the one file, and goes back to the start", ({ kind, open, download, file }) => {
    const list = links(visitor(kind));
    expect(list.find((l) => l.text === open)).toEqual({ text: open, href: `./${file}`, download: false });
    expect(list.find((l) => l.text === download)).toEqual({ text: download, href: `./${file}`, download: true });
    expect(list.find((l) => l.text === "Back to start")?.href).toBe("../../");
    expect(list.find((l) => l.text === "About this sheet")?.href).toBe("#/about");
  });

  it.each(cases)("$kind: About names what is in the file and what is not, and goes back to the sheet", ({ kind }) => {
    const html = visitor(kind, "#/about");
    expect(html).toMatch(/<h1[^>]*>About this sheet<\/h1>/);
    expect(textOf(html)).toContain("It is one file. It holds no network address, so it opens with no connection.");
    expect(links(html).find((l) => l.text === "Back to the sheet")?.href).toBe("#/");
  });

  it("says the family file shows only approved names, and the seeker file shows no names and no rent", () => {
    expect(textOf(visitor("family"))).toContain("It lists only the names the warden approved");
    expect(textOf(visitor("seeker"))).toContain("It holds no names and no rent.");
  });

  it("says Page not found for an unknown route", () => {
    for (const kind of ["family", "seeker"] as const) {
      const html = visitor(kind, "#/nope");
      expect(html).toMatch(/<h1[^>]*>Page not found<\/h1>/);
      expect(links(html).find((l) => l.text === "Back to start")?.href).toBe("../../");
    }
  });

  it("titles each route", () => {
    expect(visitorTitleOf("family", "home")).toBe("Family map · Plotwarden");
    expect(visitorTitleOf("seeker", "home")).toBe("Plot seeker map · Plotwarden");
    expect(visitorTitleOf("family", "about")).toBe("About this sheet · Family map");
    expect(visitorTitleOf("seeker", "not-found")).toBe("Page not found · Plotwarden");
  });

  it("carries no private value: the sample files hold a canary of neither fixture, and the pages name no person", () => {
    for (const kind of ["family", "seeker"] as const) {
      for (const hash of ["", "#/about"]) {
        const text = textOf(visitor(kind, hash));
        for (const name of ["Mirel Quillmoss", "Torin Pellwick", "Tavi Bramblequill", "Olin Reedwhorl", "example.invalid"]) expect(text).not.toContain(name);
      }
    }
  });
});
