// Write the two practice maps of the hub into site/src/practiceMaps.ts.
//
//   node scripts/build-practice-maps.mjs [--out <file>]
//
// The maps come from tools/site/practiceMaps.ts, which draws the practice registers with the shared sheet. The
// site may not import the registers, so the drawing is made here, once, and kept as text. The script bundles the
// tool with Vite (a server side build to a scratch folder, no server) and runs it. `tests/unit/siteCopy.test.ts`
// holds the file equal to a fresh build, so a change to the sheet or to the practice data fails until this runs.
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "vite";
import { finish, parseArgs } from "./lib/files.mjs";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");

finish(async () => {
  const args = parseArgs(process.argv.slice(2), { out: "value" });
  const out = resolve(args.out ?? join(repo, "site", "src", "practiceMaps.ts"));

  const scratch = mkdtempSync(join(tmpdir(), "plotwarden-maps-"));
  try {
    await build({
      configFile: false,
      root: repo,
      logLevel: "warn",
      build: {
        ssr: "tools/site/practiceMaps.ts",
        target: "node24",
        outDir: scratch,
        emptyOutDir: true,
        minify: false,
        sourcemap: false,
        rollupOptions: { output: { format: "es", entryFileNames: "practiceMaps.mjs" } },
      },
      ssr: { noExternal: true },
    });
    const { buildPracticeMaps } = await import(pathToFileURL(join(scratch, "practiceMaps.mjs")).href);
    const maps = buildPracticeMaps();
    const text = [
      "// Generated by scripts/build-practice-maps.mjs from the practice registers. Do not edit by hand.",
      "// Run npm run build:maps after a change to the sheet or to the practice data. A test holds this file equal to a fresh build.",
      "export const PRACTICE_MAPS = {",
      `  church: ${JSON.stringify(maps.church)},`,
      `  garden: ${JSON.stringify(maps.garden)},`,
      "} as const;",
      "",
    ].join("\n");
    writeFileSync(out, text, "utf8");
    console.log(`build-practice-maps: wrote ${out}`);
    return 0;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
});
